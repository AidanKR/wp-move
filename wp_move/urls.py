"""Old WordPress URL -> new static path: the map, internal-link rewriting, and redirect files."""
from __future__ import annotations

import csv
import json
import os
import urllib.parse

STYLES = ("keep", "slug")
UPLOADS = "/wp-content/uploads/"


def split_link(link: str | None, home: str) -> tuple[str, str] | None:
    """(decoded path, query) for a link on this site, else None."""
    if not link:
        return None
    h = urllib.parse.urlsplit(home)
    u = urllib.parse.urlsplit(urllib.parse.urljoin(home + "/", link))
    if u.netloc != h.netloc:
        return None
    base = h.path.rstrip("/")
    path = urllib.parse.unquote(u.path)
    if base and not path.startswith(base):
        return None
    path = path[len(base):] or "/"
    return path, u.query


def new_path(kind: str, item: dict, home: str, style: str, slug: str, page_rel: str | None) -> str:
    """Site-relative path the item will live at, always with a trailing slash."""
    if style == "keep":
        parts = split_link(item.get("link"), home)
        if parts and not parts[1] and parts[0] != "/":
            return parts[0] if parts[0].endswith("/") else parts[0] + "/"
    if kind == "pages":
        return f"/{page_rel or slug}/"
    return f"/posts/{slug}/"


class LinkMap:
    """Rewrites links that point at old post/page URLs to their new paths."""

    def __init__(self, home: str):
        self.home = home
        self.by_path: dict[str, str] = {}
        self.by_query: dict[str, str] = {}

    def add(self, item: dict, kind: str, target: str) -> None:
        parts = split_link(item.get("link"), self.home)
        if parts and not parts[1]:
            self.by_path[parts[0].rstrip("/") or "/"] = target
        self.by_query[f"p={item['id']}"] = target
        if kind == "pages":
            self.by_query[f"page_id={item['id']}"] = target

    def rewrite(self, url: str | None) -> str | None:
        parts = split_link(url, self.home)
        if not parts:
            return None
        path, query = parts
        frag = urllib.parse.urlsplit(url).fragment
        target = None
        if query and path in ("/", "/index.php"):
            target = self.by_query.get(query)
        else:
            # A permalink with a query (e.g. ?replytocom=) still means that post; the query is dropped.
            target = self.by_path.get(path.rstrip("/") or "/")
        if not target:
            return None
        return target + (f"#{frag}" if frag else "")


def build_redirects(entries: list[dict]) -> list[dict]:
    """Redirect rules from url-map entries (only items that had a public URL)."""
    rules, seen = [], set()

    def add(src: str, query: str, dst: str, kind: str) -> None:
        key = (src, query)
        if key not in seen and (src != dst or query):
            seen.add(key)
            rules.append({"from": src, "query": query, "to": dst, "kind": kind})

    for e in entries:
        if e["status"] != "publish" or not e["new_path"]:
            continue
        if e["old_path"] and not e["old_query"]:
            add(e["old_path"], "", e["new_path"], "permalink")
        add("/", f"p={e['wp_id']}", e["new_path"], "post-id")
        if e["type"] == "page":
            add("/", f"page_id={e['wp_id']}", e["new_path"], "page-id")
    rules.append({"from": UPLOADS + "*", "query": "", "to": "/media/:splat", "kind": "uploads"})
    return rules


def _enc(path: str) -> str:
    return urllib.parse.quote(path, safe="/-._~:*")


def _nq(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_files(out: str, entries: list[dict], rules: list[dict], unmapped: list[dict]) -> dict:
    d = os.path.join(out, "redirects")
    os.makedirs(d, exist_ok=True)

    path_rules = [r for r in rules if not r["query"] and r["kind"] != "uploads"]
    query_rules = [r for r in rules if r["query"]]

    with open(os.path.join(d, "_redirects"), "w", encoding="utf-8") as f:
        f.write("# Generated by wp-move. Old WordPress URLs -> new paths.\n")
        for r in path_rules:
            f.write(f"{_enc(r['from'])} {_enc(r['to'])} 301\n")
        f.write("# Query-string rules use Netlify's syntax; other hosts may ignore them.\n")
        for r in query_rules:
            f.write(f"/ {r['query']} {_enc(r['to'])} 301\n")
        f.write(f"{UPLOADS}* /media/:splat 301\n")

    # nginx: maps go in the http{} context, the snippet in server{}.
    with open(os.path.join(d, "nginx-maps.conf"), "w", encoding="utf-8") as f:
        f.write("# Generated by wp-move. Include inside http { }.\n")
        longest = max((len(_nq(r["from"]).encode()) for r in rules), default=0)
        bucket = 64
        while bucket < longest + 16:
            bucket *= 2
        if bucket > 64:
            f.write("# Long URL keys need a bigger hash bucket. Remove this line if your http {} already sets it.\n")
            f.write(f"map_hash_bucket_size {bucket};\n")
        f.write("map $uri $wpmove_path {\n    default \"\";\n")
        for r in path_rules:
            f.write(f"    {_nq(r['from'])} {_nq(_enc(r['to']))};\n")
            if r["from"].endswith("/") and r["from"] != "/":
                f.write(f"    {_nq(r['from'].rstrip('/'))} {_nq(_enc(r['to']))};\n")
        f.write("}\nmap $request_uri $wpmove_query {\n    default \"\";\n")
        for r in query_rules:
            for prefix in ("/", "/index.php"):
                f.write(f"    {_nq(prefix + '?' + r['query'])} {_nq(_enc(r['to']))};\n")
        f.write("}\n")
    with open(os.path.join(d, "nginx-server.conf"), "w", encoding="utf-8") as f:
        f.write("# Generated by wp-move. Include inside server { }.\n")
        f.write("if ($wpmove_query) { return 301 $wpmove_query; }\n")
        f.write("if ($wpmove_path) { return 301 $wpmove_path; }\n")
        f.write("location ^~ /wp-content/uploads/ { rewrite ^/wp-content/uploads/(.*)$ /media/$1 permanent; }\n")

    fields = ["wp_id", "type", "status", "old_url", "old_path", "old_query", "new_path", "out_path"]
    with open(os.path.join(d, "url-map.csv"), "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        w.writerows(entries)
    with open(os.path.join(d, "unmapped.json"), "w", encoding="utf-8") as f:
        json.dump(unmapped, f, ensure_ascii=False, indent=1)
    return {"path_rules": len(path_rules), "query_rules": len(query_rules), "unmapped": len(unmapped)}
